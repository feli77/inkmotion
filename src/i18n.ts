const localeStorageKey = 'inkmotion.locale.v1';
let currentLocale: Locale = 'en';

export function getLocale(): Locale {
  return currentLocale;
}

export function resolveLocale(preferences: readonly string[]): Locale {
  for (const preference of preferences) {
    const language = preference.toLowerCase();
    const exact = locales.find(locale => locale.code.toLowerCase() === language);
    if (exact) return exact.code;
    if (language === 'zh' || language.startsWith('zh-')) {
      if (language.split('-').includes('hans')) return 'zh-CN';
      return /(?:^|-)(?:hant|tw|hk|mo)(?:-|$)/.test(language) ? 'zh-TW' : 'zh-CN';
    }
    const base = language.split('-')[0];
    const match = locales.find(locale => locale.code.split('-')[0] === base);
    if (match) return match.code;
  }
  return 'en';
}

export function getPreferredLocale(): Locale {
  try {
    const saved = localStorage.getItem(localeStorageKey);
    const match = locales.find(locale => locale.code === saved);
    if (match) return match.code;
  } catch { /* Browser language detection still works when storage is unavailable. */ }
  return resolveLocale(navigator.languages.length ? navigator.languages : [navigator.language]);
}

export function setLocale(locale: Locale, persist = true): void {
  currentLocale = locale;
  document.documentElement.lang = locale;
  document.title = `InkMotion · ${t('app.title')}`;
  document.querySelector<HTMLMetaElement>('meta[name="description"]')?.setAttribute('content', t('app.metaDescription'));
  if (persist) {
    try { localStorage.setItem(localeStorageKey, locale); } catch { /* Nonessential. */ }
  }
}

export function t(key: MessageKey, values: Record<string, string | number> = {}): string {
  const message = dictionaries[currentLocale][key] ?? zhCN[key];
  return message.replace(/\{(\w+)\}/g, (match, name: string) => String(values[name] ?? match));
}
